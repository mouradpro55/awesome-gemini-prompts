def macro_value(text: str, c_type: str = "east") -> int:
    table = WEST_TABLE if c_type == "west" else EAST_TABLE
    return sum(table.get(char, 0) for char in text)

def digital_root(n: int) -> int:
    if n == 0:
        return 0
    return 1 + ((n - 1) % 9)

def bast_extended_value(text: str, c_type: str = "east") -> int:
    expanded = "".join(BAST_MAPPING.get(char, "") for char in text if not char.isspace())
    return macro_value(expanded, c_type)
